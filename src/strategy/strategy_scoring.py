# ============================================================
# RISK SCORE
# ============================================================

def calculate_risk_scores(
    strategies: List[Dict[str, Any]]
) -> Dict[int, float]:
    """
    Calculate strategic risk scores.

    Fewer pit stops generally means lower operational risk.

    STAY_OUT receives the highest baseline score.

    One-stop strategies receive a moderate score.
    """

    scores = {}

    for index, strategy in enumerate(
        strategies
    ):

        stops = strategy[
            "stops"
        ]

        if stops == 0:

            scores[index] = 95.0

        elif stops == 1:

            scores[index] = 85.0

        else:

            scores[index] = 70.0

    return scores


# ============================================================
# CALCULATE OVERALL SCORE
# ============================================================

def calculate_overall_score(
    pace_score: float,
    tyre_score: float,
    pit_score: float,
    traffic_score: float,
    position_score: float,
    degradation_score: float,
    risk_score: float
) -> float:
    """
    Calculate the weighted unified strategy score.
    """

    score = (

        pace_score
        * PACE_WEIGHT

        +

        tyre_score
        * TYRE_WEIGHT

        +

        pit_score
        * PIT_WEIGHT

        +

        traffic_score
        * TRAFFIC_WEIGHT

        +

        position_score
        * POSITION_WEIGHT

        +

        degradation_score
        * DEGRADATION_WEIGHT

        +

        risk_score
        * RISK_WEIGHT

    )

    return round(

        score,

        2

    )


# ============================================================
# SCORE ALL STRATEGIES
# ============================================================

def score_strategies(
    strategies: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """
    Score every strategy generated by Phase 3.5.
    """

    validate_strategies(
        strategies
    )

    pace_scores = (
        calculate_pace_scores(
            strategies
        )
    )

    tyre_scores = (
        calculate_tyre_scores(
            strategies
        )
    )

    pit_scores = (
        calculate_pit_scores(
            strategies
        )
    )

    traffic_scores = (
        calculate_traffic_scores(
            strategies
        )
    )

    position_scores = (
        calculate_position_scores(
            strategies
        )
    )

    degradation_scores = (
        calculate_degradation_scores(
            strategies
        )
    )

    risk_scores = (
        calculate_risk_scores(
            strategies
        )
    )

    scored_strategies = []

    for index, strategy in enumerate(
        strategies
    ):

        result = strategy.copy()

        result[
            "pace_score"
        ] = pace_scores[index]

        result[
            "tyre_score"
        ] = tyre_scores[index]

        result[
            "pit_score"
        ] = pit_scores[index]

        result[
            "traffic_score"
        ] = traffic_scores[index]

        result[
            "position_score"
        ] = position_scores[index]

        result[
            "degradation_score"
        ] = degradation_scores[index]

        result[
            "risk_score"
        ] = risk_scores[index]

        result[
            "overall_score"
        ] = calculate_overall_score(

            pace_score=pace_scores[index],

            tyre_score=tyre_scores[index],

            pit_score=pit_scores[index],

            traffic_score=traffic_scores[index],

            position_score=position_scores[index],

            degradation_score=(
                degradation_scores[index]
            ),

            risk_score=risk_scores[index]

        )

        scored_strategies.append(
            result
        )

    # --------------------------------------------------------
    # RANK BY OVERALL SCORE
    # --------------------------------------------------------

    scored_strategies.sort(

        key=lambda strategy:
        strategy[
            "overall_score"
        ],

        reverse=True

    )

    for rank, strategy in enumerate(

        scored_strategies,

        start=1

    ):

        strategy[
            "score_rank"
        ] = rank

    return scored_strategies


# ============================================================
# GET BEST SCORED STRATEGY
# ============================================================

def get_best_scored_strategy(
    strategies: List[Dict[str, Any]]
) -> Dict[str, Any] | None:
    """
    Return the highest-scoring strategy.
    """

    if not strategies:

        return None

    return max(

        strategies,

        key=lambda strategy:
        strategy[
            "overall_score"
        ]

    )


# ============================================================
# COMPLETE STRATEGY SCORING
# ============================================================

def run_strategy_scoring(
    strategies: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """
    Run the complete Phase 3.6 scoring pipeline.
    """

    scored_strategies = score_strategies(
        strategies
    )

    best_strategy = (
        get_best_scored_strategy(
            scored_strategies
        )
    )

    return {

        "strategy_count":
            len(scored_strategies),

        "strategies":
            scored_strategies,

        "best_strategy":
            best_strategy,

        "best_score":
            (
                best_strategy[
                    "overall_score"
                ]

                if best_strategy

                else None
            )

    }


