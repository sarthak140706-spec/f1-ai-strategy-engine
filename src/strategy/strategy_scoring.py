"""
strategy_scoring.py

PHASE 3.6 — STRATEGY SCORING

Purpose
-------
Convert the projected strategies generated by Phase 3.5 into
a unified strategy score.

The scoring system considers:

    Pace Performance
    Tyre Performance
    Pit Cost
    Traffic Impact
    Track Position
    Degradation
    Risk

The final score is normalized to 0–100.

Higher score = better strategic option.

This module does NOT:
    - simulate strategies
    - make the final AI recommendation
    - expose an API
    - handle frontend logic

Those responsibilities belong to other Phase 3 modules.
"""

from typing import Dict, Any, List


# ============================================================
# SCORE WEIGHTS
# ============================================================

PACE_WEIGHT = 0.25

TYRE_WEIGHT = 0.15

PIT_WEIGHT = 0.15

TRAFFIC_WEIGHT = 0.10

POSITION_WEIGHT = 0.10

DEGRADATION_WEIGHT = 0.10

RISK_WEIGHT = 0.15


# ============================================================
# INPUT VALIDATION
# ============================================================

def validate_strategies(
    strategies: List[Dict[str, Any]]
) -> None:
    """
    Validate the strategy list received from Phase 3.5.
    """

    if not strategies:

        raise ValueError(
            "Strategy list cannot be empty."
        )

    required_fields = [

        "strategy",

        "projected_total_time",

        "pit_loss",

        "degradation_impact",

        "stops"

    ]

    for strategy in strategies:

        for field in required_fields:

            if field not in strategy:

                raise ValueError(

                    f"Missing required strategy "
                    f"field: {field}"

                )


# ============================================================
# NORMALIZATION
# ============================================================

def normalize_lower_is_better(
    value: float,
    minimum: float,
    maximum: float
) -> float:
    """
    Convert a lower-is-better metric into a 0–100 score.

    Lower value -> higher score.
    """

    if maximum == minimum:

        return 100.0

    score = (

        (maximum - value)

        /

        (maximum - minimum)

    ) * 100

    return round(

        max(
            0.0,
            min(
                100.0,
                score
            )
        ),

        2

    )


def normalize_higher_is_better(
    value: float,
    minimum: float,
    maximum: float
) -> float:
    """
    Convert a higher-is-better metric into a 0–100 score.
    """

    if maximum == minimum:

        return 100.0

    score = (

        (value - minimum)

        /

        (maximum - minimum)

    ) * 100

    return round(

        max(
            0.0,
            min(
                100.0,
                score
            )
        ),

        2

    )


# ============================================================
# PACE SCORE
# ============================================================

def calculate_pace_scores(
    strategies: List[Dict[str, Any]]
) -> Dict[int, float]:
    """
    Calculate pace scores.

    Lower projected total time = better pace score.
    """

    times = [

        strategy[
            "projected_total_time"
        ]

        for strategy in strategies

    ]

    minimum = min(times)

    maximum = max(times)

    scores = {}

    for index, strategy in enumerate(
        strategies
    ):

        scores[index] = normalize_lower_is_better(

            strategy[
                "projected_total_time"
            ],

            minimum,

            maximum

        )

    return scores


# ============================================================
# TYRE PERFORMANCE SCORE
# ============================================================

def calculate_tyre_scores(
    strategies: List[Dict[str, Any]]
) -> Dict[int, float]:
    """
    Calculate tyre-performance scores.

    Lower degradation impact receives a higher score.
    """

